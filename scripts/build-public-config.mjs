/**
 * Derive config/public.config.json — the only slice of the agent config that is
 * safe to ship to a browser.
 *
 * The client panels need a handful of facts: the latency budget, each agent's
 * label and tool list, the adversarial button list. Importing
 * agent.config.json to get them bundles the WHOLE file into the client
 * JavaScript, including every system prompt, the verifier's lettered checklist,
 * and all guardrail patterns. Tree-shaking cannot help — they are properties of
 * one JSON object, not separate exports.
 *
 * Guardrail 8 says the agent must never reveal its instructions. Shipping them
 * in the page bundle contradicts that regardless of what the agent says, and
 * anyone who opened devtools would find them.
 *
 * Run by `prebuild`, so a stale file cannot reach a deployment, and guarded by
 * a test that fails if the committed output no longer matches the source.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);

export function derivePublicConfig(config) {
  return {
    _notice:
      'GENERATED by scripts/build-public-config.mjs — do not edit. The client-safe slice of ' +
      'agent.config.json. Prompts, guardrail patterns and the verifier checklist are ' +
      'deliberately absent: importing the full config into a client component would ship them ' +
      'in the browser bundle.',
    organisation: {
      name: config.organisation.name,
      shortName: config.organisation.shortName,
      disclaimer: config.organisation.disclaimer,
      referenceCity: config.organisation.referenceCity,
    },
    models: Object.fromEntries(
      Object.entries(config.models)
        .filter(([k]) => !k.startsWith('$'))
        .map(([tier, m]) => [tier, { id: m.id, usdPerMillion: m.usdPerMillion }]),
    ),
    // Labels and tool NAMES only — never the prompts.
    agents: Object.fromEntries(
      Object.entries(config.agents)
        .filter(([k]) => !k.startsWith('$'))
        .map(([key, a]) => [key, { label: a.label, tools: a.tools ?? [] }]),
    ),
    // Ids, labels and actions only — never the patterns, which would be a map
    // of exactly what to say to get past them.
    guardrails: Object.fromEntries(
      Object.entries(config.guardrails)
        .filter(([k]) => !k.startsWith('$'))
        .map(([key, g]) => [key, { id: g.id, label: g.label, action: g.action }]),
    ),
    verifier: {
      // Which intents skip the verifier is shown in the UI to explain the
      // audio-path decision. The verifier's own prompt is not included.
      skipForIntents: config.verifier.shouldRun.skipForIntents,
      maxRetries: config.verifier.maxRetries,
    },
    limits: config.limits,
    latencyBudgetMs: config.latencyBudgetMs,
    demo: config.demo,
    toolCount: new Set(
      Object.values(config.agents).flatMap((a) => (a && a.tools) || []),
    ).size,
  };
}

const config = JSON.parse(readFileSync(new URL('config/agent.config.json', root), 'utf8'));
const output = `${JSON.stringify(derivePublicConfig(config), null, 2)}\n`;
writeFileSync(new URL('config/public.config.json', root), output);
console.log(`Wrote config/public.config.json (${(output.length / 1024).toFixed(1)}K)`);
